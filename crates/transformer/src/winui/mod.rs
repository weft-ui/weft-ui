//! WinUI 3 view backend for Windows, driven by the native kernel's ops.
//!
//! The logic layer uses
//! [`crate::bridge::remote_module`].
//! This backend generates one `Generated.cs` for the whole app, compiled against
//! `Weft.WinUI` (`native/windows/Weft.WinUI`) in `apps/windows/weft/`.
//! Each template becomes a scope class `S{n}` that constructs its static tree,
//! retains elements with value slots, and applies `set` ops to their properties.
//! Mount points are registered with regions; the session mounts child scopes.
//!
//! | Element    | Weft.WinUI wrapper | Native control              |
//! | ---------- | ------------------ | --------------------------- |
//! | `Column`   | `WeftStack(true)`  | Vertical `WeftLinearPanel` |
//! | `Row`      | `WeftStack(false)` | Horizontal `WeftLinearPanel` |
//! | `Stack`    | `WeftOverlay`      | `WeftStackPanel`            |
//! | `Scroll`   | `WeftScroll`       | `ScrollViewer`             |
//! | `Spacer`   | `WeftSpacer`       | Empty `FrameworkElement`   |
//! | `Text`     | `WeftText`         | `TextBlock`                 |
//! | `Span`     | `WeftSpan`         | `Run` in its parent        |
//! | `Button`   | `WeftButton`       | `Button`                    |
//! | `Input`    | `WeftInput`        | `TextBox` or `PasswordBox`   |
//! | `Checkbox` | `WeftCheckbox`     | Controlled `CheckBox`       |
//! | `Image`    | `WeftImage`        | `Image` with `BitmapImage`  |
//!
//! The public entry point, `WeftApp.Start()`, starts the kernel and returns
//! the app's root view. Layout defaults and controlled editing live in the
//! wrappers, not in the generated code.

mod csharp;
mod view;

use crate::elements::Element;
use crate::transform::{Context, OutputFile};
use crate::view::{Template, ValueType, ViewLayout, ViewNodeKind};

use csharp::Code;

/// Path of the generated views, relative to `apps/windows/weft/`.
const VIEWS: &str = "Generated.cs";

/// Generates the WinUI views for the app.
///
/// # Panics
///
/// Panics without a layout in `cx`.
#[must_use]
pub fn transform(cx: &Context<'_>) -> Vec<OutputFile> {
    let layout = cx.layout.expect("the WinUI views need the layout");
    vec![OutputFile {
        path: VIEWS.to_owned(),
        contents: generate(layout, cx.program.app.as_ref()),
    }]
}

fn generate(layout: &ViewLayout, app: Option<&crate::ir::Application>) -> String {
    let mut out = Code::new();
    out.writer
        .line("// Generated by Weft UI from the app's .weft files; every build rewrites it.");
    out.writer.blank();
    out.writer.line("#nullable enable");
    out.writer.blank();
    out.writer.line("using Weft.WinUI;");
    out.writer.blank();
    out.writer.line("namespace Weft.Generated;");
    out.writer.blank();
    out.writer.line("/// <summary>The app's views, implementing the layout the bundle was compiled with.</summary>");
    out.open("public static class WeftApp");
    out.writer.line("/// <summary>Hash of the layout; the kernel refuses bundles compiled with another layout.</summary>");
    out.writer.line(format_args!(
        "public const ulong LayoutHash = 0x{:016x}UL;",
        layout.hash()
    ));
    out.writer.line(format_args!(
        "public const bool SafeArea = {};",
        layout.safe_area()
    ));
    out.writer.blank();
    out.writer.line(
        "/// <summary>Starts the app's bundle in the kernel and returns its root view.</summary>",
    );
    let has_theme = !layout.theme().is_empty();
    let tabs = app.and_then(|app| app.tabs.as_ref());
    let tab_arg = tabs
        .map(|tabs| {
            let items = tabs
                .iter()
                .map(|tab| {
                    format!(
                        "new({}, {}, {})",
                        csharp::string(&tab.title),
                        csharp::string(&tab.icon),
                        csharp::string(&tab.active_icon)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!(", tabs: [{items}]")
        })
        .unwrap_or_default();
    if has_theme {
        out.writer
            .line("public static Microsoft.UI.Xaml.UIElement Start() =>");
        out.writer.indent();
        out.open("WeftSession.Start(LayoutHash, SafeArea, MakeScope, WeftTheme.Register(new()");
        for (name, light, dark) in layout.theme() {
            out.writer.line(format_args!(
                "[{}] = ({}, {}),",
                csharp::string(name),
                csharp::rgba(*light),
                csharp::rgba(*dark)
            ));
        }
        out.close(format!("){tab_arg});"));
        out.writer.dedent();
    } else {
        out.writer.line(format_args!("public static Microsoft.UI.Xaml.UIElement Start() => WeftSession.Start(LayoutHash, SafeArea, MakeScope{tab_arg});"));
    }
    out.writer.blank();
    out.writer
        .line("/// <summary>Scope of a <c>create</c> op.</summary>");
    out.open("private static WeftScope? MakeScope(uint template, uint id, WeftSession session) => template switch");
    for index in 0..layout.templates().len() {
        out.writer
            .line(format_args!("{index} => new S{index}(id, session),"));
    }
    out.writer.line("_ => null,");
    out.close(";");
    out.close("");
    for (index, template) in layout.templates().iter().enumerate() {
        out.writer.blank();
        out.writer
            .line(format_args!("// {index} {}", template.label));
        out.writer.blank();
        scope(&mut out, index, template, has_theme);
    }
    out.writer.finish()
}

/// The scope class `S{index}` of `template`.
fn scope(out: &mut Code, index: usize, template: &Template, has_theme: bool) {
    out.open(format_args!("file sealed class S{index} : WeftScope"));
    for (node, view) in template.nodes.iter().enumerate() {
        let mut slots = template
            .values
            .iter()
            .filter(|v| v.node as usize == node)
            .peekable();
        if slots.peek().is_none() {
            continue;
        }
        let ViewNodeKind::Element { element, .. } = view.kind else {
            unreachable!("value slots belong to elements");
        };
        for value in slots {
            out.writer
                .line(format_args!("// {}.{}", element.name(), value.prop));
        }
        out.writer.line(format_args!(
            "private readonly {} n{node};",
            view::wrapper(element)
        ));
    }
    if !template.values.is_empty() {
        out.writer.blank();
    }
    let points = if template.points.is_empty() {
        String::new()
    } else {
        format!(", points: {}", template.points.len())
    };
    out.open(format_args!(
        "public S{index}(uint id, WeftSession session) : base(id, session{points})"
    ));
    view::body(out, template, has_theme);
    out.close("");
    if !template.values.is_empty() {
        out.writer.blank();
        out.open("public override void Apply(int slot, WeftValue value)");
        out.open("switch (slot)");
        for (slot, value) in template.values.iter().enumerate() {
            let ViewNodeKind::Element { element, .. } = template.nodes[value.node as usize].kind
            else {
                unreachable!("value slots belong to elements");
            };
            if matches!(element, Element::List | Element::Grid) && value.prop == "refreshing" {
                continue;
            }
            let accessor = match value.ty {
                ValueType::Int | ValueType::Float => "value.Number",
                ValueType::Bool => "value.Bool",
                ValueType::String => "value.String",
                ValueType::Color => "value.Color",
                ValueType::Strings => "value.Strings",
            };
            let expression = std::fmt::from_fn(|out| match view::union(element, value.prop) {
                Some(ty) => write!(out, "WeftUnions.Parse{ty}({accessor})"),
                None => out.write_str(accessor),
            });
            out.writer.line(format_args!(
                "case {slot}: n{}.{} = {expression}; break;",
                value.node,
                view::property(value.prop),
            ));
        }
        out.close("");
        out.close("");
    }
    out.close("");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::transform::Platform;
    use crate::{AppOptions, compile_app};
    use weft_ui_parser::MemoryLoader;

    fn csharp(source: &str) -> String {
        let mut loader = MemoryLoader::new();
        loader.insert("App.weft", source);
        let compilation = crate::check(weft_ui_parser::load(&["App.weft"], &mut loader));
        let Some(program) = &compilation.program else {
            panic!("{}", compilation.render_diagnostics());
        };
        generate(&ViewLayout::new(program), program.app.as_ref())
    }

    #[test]
    fn page_navigation_bar_is_separate_from_content() {
        let code = csharp(
            r#"event Action()
            app Notes { start = Home }
            page Home(title: String = "Home", disabled: Bool = false, icon: String = "") {
                NavBar(title = title, hidden = true) {
                    BarButton(label = title, disabled = disabled, icon = icon, onTap = Action())
                }
                Text("body")
            }"#,
        );
        for expected in [
            "private readonly WeftNavigationBar n0;",
            "private readonly WeftBarButton n1;",
            "n0.Hidden = true;",
            "NavigationBar = n0.Element;",
            "n1 = new WeftBarButton(() => Dispatch(0));",
            "n0.Add(n1);",
            "Roots.Add(n2.Element);",
            "n0.Title = value.String; break;",
            "n1.Label = value.String; break;",
            "n1.Disabled = value.Bool; break;",
            "n1.Icon = value.String; break;",
        ] {
            assert!(code.contains(expected), "missing {expected:?}\n{code}");
        }
        assert!(!code.contains("Roots.Add(n0.Element);"), "{code}");
    }

    #[test]
    fn registers_safe_area_opt_out() {
        let mut loader = MemoryLoader::new();
        loader.insert("App.weft", "component App() { Text(\"hello\") }");
        let output = compile_app(
            weft_ui_parser::load(&["App.weft"], &mut loader),
            Platform::Windows,
            &AppOptions {
                safe_area: false,
                ..AppOptions::default()
            },
        );
        let generated = output
            .views
            .iter()
            .find(|view| view.path == VIEWS)
            .unwrap_or_else(|| panic!("{}", output.compilation.render_diagnostics()));
        for expected in [
            "public const bool SafeArea = false;",
            "WeftSession.Start(LayoutHash, SafeArea, MakeScope);",
        ] {
            assert!(
                generated.contents.contains(expected),
                "missing {expected:?}"
            );
        }
    }

    #[test]
    fn wrappers_inline_constants_before_attaching() {
        let code = csharp(
            r##"component A() {
                Column(padding = 4, gap = 2, width = 100, height = 80, background = "#abc") {
                    Row(gap = 1) {
                        Text("hello", color = "#12345680", size = 12, weight = "bold")
                        Button(disabled = true) { Text("button") }
                        Input("", placeholder = "hint", disabled = true)
                        Checkbox(false, disabled = true)
                        Image("image.png", width = 20, height = 30)
                    }
                }
            }"##,
        );
        for expected in [
            "var n0 = new WeftStack(vertical: true);",
            "n0.Padding = 4;",
            "n0.Width = 100;",
            "n0.Height = 80;",
            "n0.Background = WeftColor.Rgba(0xaabbccffu);\n        n0.Gap = 2;\n        Roots.Add(n0.Element);",
            "var n1 = new WeftStack(vertical: false);",
            "n2.Color = WeftColor.Rgba(0x12345680u);\n        n2.Size = 12;\n        n2.Weight = WeftWeight.Bold;\n        n2.Value = \"hello\";\n        n1.Children.Add(n2.Element);",
            "var n3 = new WeftButton(null);",
            "n3.Disabled = true;",
            "n5 = new WeftInput(v => Dispatch(0, WeftValue.Of(v)));",
            "n5.Placeholder = \"hint\";",
            "n5.Disabled = true;",
            "n6 = new WeftCheckbox(v => Dispatch(1, WeftValue.Of(v)));",
            "n6.Disabled = true;",
            "var n7 = new WeftImage();",
            "n7.Src = \"image.png\";",
            "n7.Width = 20;",
            "n7.Height = 30;",
            "case 0: n5.Value = value.String; break;",
            "case 1: n6.Checked = value.Bool; break;",
        ] {
            assert!(code.contains(expected), "missing {expected:?}\n{code}");
        }
        assert!(!code.contains("points:"), "{code}");
        assert_eq!(code.matches("private readonly").count(), 2, "{code}");
    }

    #[test]
    fn value_slots_share_one_field_and_use_typed_accessors() {
        let code = csharp(
            r#"type Weight = "regular" | "light" | "medium" | "semibold" | "bold"
            component A(text: String, size: Int, weight: Weight, color: String) {
                Text(text, size = size, weight = weight, color = color)
            }"#,
        );
        assert_eq!(
            code.matches("private readonly WeftText n0;").count(),
            1,
            "{code}"
        );
        for expected in [
            "// Text.value",
            "// Text.size",
            "// Text.weight",
            "// Text.color",
            "n0 = new WeftText();",
            "n0.Value = value.String; break;",
            "n0.Size = value.Number; break;",
            "n0.Weight = WeftUnions.ParseWeight(value.String); break;",
            "n0.Color = value.Color; break;",
        ] {
            assert!(code.contains(expected), "missing {expected:?}\n{code}");
        }
        assert!(!code.contains("var n0"), "{code}");
    }

    #[test]
    fn text_properties_and_spans_keep_independent_value_slots() {
        let code = csharp(
            r##"
                type Weight = "regular" | "light" | "medium" | "semibold" | "bold"
                type Decoration = "none" | "underline" | "lineThrough"
                type TextAlign = "start" | "center" | "end"
                theme { accent = "#158" }
                component A(label: String, weight: Weight, decoration: Decoration, italic: Bool,
                            align: TextAlign, lines: Int, height: Int, color: String) {
                    Text(weight = weight, decoration = "lineThrough", align = align,
                         maxLines = lines, lineHeight = height) {
                        Span("before ", weight = "bold", color = theme.accent)
                        Span(label, weight = weight, italic = italic, decoration = decoration,
                             size = 14, color = color)
                        Span(" after", decoration = "underline")
                    }
                }
            "##,
        );
        for expected in [
            "n0 = new WeftText();",
            "n0.Decoration = WeftDecoration.LineThrough;",
            "var n1 = new WeftSpan(n0);\n        TrackColors(n1);",
            "n1.Weight = WeftWeight.Bold;",
            "n1.Color = WeftColor.Token(\"accent\");",
            "private readonly WeftSpan n2;",
            "n2 = new WeftSpan(n0);\n        TrackColors(n2);",
            "n2.Size = 14;",
            "var n3 = new WeftSpan(n0);",
            "n3.Decoration = WeftDecoration.Underline;",
            "n0.Weight = WeftUnions.ParseWeight(value.String); break;",
            "n0.Align = WeftUnions.ParseTextAlign(value.String); break;",
            "n0.MaxLines = value.Number; break;",
            "n0.LineHeight = value.Number; break;",
            "n2.Value = value.String; break;",
            "n2.Weight = WeftUnions.ParseWeight(value.String); break;",
            "n2.Italic = value.Bool; break;",
            "n2.Decoration = WeftUnions.ParseDecoration(value.String); break;",
            "n2.Color = value.Color; break;",
        ] {
            assert!(code.contains(expected), "missing {expected:?}\n{code}");
        }
        assert_eq!(code.matches(".Add(").count(), 1, "{code}");
        assert!(code.contains("Roots.Add(n0.Element);"), "{code}");
    }

    #[test]
    fn strings_are_escaped_and_never_interpolated() {
        let code = csharp(r#"component A() { Text("say \"hi\" \\{x} \u{7}") }"#);
        assert!(
            code.contains(r#"n0.Value = "say \"hi\" \\{x} \u0007";"#),
            "{code}"
        );
    }
}
