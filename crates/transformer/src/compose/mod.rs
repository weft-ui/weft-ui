//! Jetpack Compose view backend for Android.
//!
//! The native kernel runs the logic from
//! [`crate::bridge::remote_module`]
//! and drives the views in `Generated.kt`, compiled into the `weft` Android
//! library module against the `net.mioyi.weftui` shell.
//!
//! Each layout template `n` becomes `S{n}`, a `WeftScope` subclass with Compose
//! state for its value slots and mount points, and `V{n}`, a composable that
//! renders the template's static tree while reading that state. `WeftApp`
//! starts the kernel with the bundle and renders the root component.

mod kotlin;
mod view;

use std::fmt;

use crate::transform::{Context, OutputFile};
use crate::view::{PointKind, Template, TemplateKind, ValueType, ViewLayout, ViewNodeKind};

use kotlin::Code;

/// Path of the generated views, relative to `apps/android/weft/`.
const VIEWS: &str = "src/main/kotlin/Generated.kt";

/// Generates the Jetpack Compose views for the app.
///
/// # Panics
///
/// Panics without a layout in `cx`.
#[must_use]
pub fn transform(cx: &Context<'_>) -> Vec<OutputFile> {
    let layout = cx.layout.expect("the Compose views need the layout");
    vec![OutputFile {
        path: VIEWS.to_owned(),
        contents: generate(layout, cx.program),
    }]
}

fn generate(layout: &ViewLayout, program: &crate::ir::Program) -> String {
    let mut out = Code::new();
    out.writer
        .line("// Generated by Weft UI from the app's .weft files; every build rewrites it.");
    out.writer.blank();
    out.writer.line("package net.mioyi.weftui.generated");
    out.writer.blank();
    if program.app.is_some() {
        out.writer
            .line("import androidx.compose.foundation.layout.Box");
        out.writer
            .line("import androidx.compose.foundation.layout.imePadding");
    }
    out.writer
        .line("import androidx.compose.runtime.Composable");
    out.writer.line("import androidx.compose.runtime.getValue");
    out.writer.line("import androidx.compose.runtime.key");
    out.writer
        .line("import androidx.compose.runtime.mutableFloatStateOf");
    out.writer
        .line("import androidx.compose.runtime.mutableStateOf");
    out.writer.line("import androidx.compose.runtime.setValue");
    out.writer.line("import androidx.compose.ui.Modifier");
    out.writer.line("import androidx.compose.ui.graphics.Color");
    out.writer.line("import net.mioyi.weftui.*");
    out.writer.blank();
    let theme = layout.theme();
    if !theme.is_empty() {
        out.open("private val appTheme = WeftTheme.register(mapOf(");
        for (name, light, dark) in theme {
            let name = fmt::from_fn(|f| kotlin::string(f, name));
            let light = kotlin::color(*light);
            let dark = kotlin::color(*dark);
            out.writer
                .line(format_args!("{name} to ({light} to {dark}),"));
        }
        out.close("))");
        out.writer.blank();
    }
    let tabs = program.app.as_ref().and_then(|app| app.tabs.as_ref());
    if let Some(tabs) = tabs {
        out.open("private val appTabs = listOf(");
        for tab in tabs {
            let title = fmt::from_fn(|f| kotlin::string(f, &tab.title));
            let icon = fmt::from_fn(|f| kotlin::string(f, &tab.icon));
            let active_icon = fmt::from_fn(|f| kotlin::string(f, &tab.active_icon));
            out.writer
                .line(format_args!("WeftTab({title}, {icon}, {active_icon}),"));
        }
        out.close(")");
        out.writer.blank();
    }
    out.writer.line("/** Root view of the app: starts the kernel with the bundle and renders the root component. */");
    out.writer.line("@Composable");
    out.open("fun WeftApp() {");
    let theme_arg = if theme.is_empty() {
        ""
    } else {
        ", theme = appTheme"
    };
    let tabs_arg = if tabs.is_some() {
        ", tabs = appTabs"
    } else {
        ""
    };
    if program.app.is_some() {
        out.open("Box(Modifier.imePadding()) {");
    }
    out.writer.line(format_args!(
        "WeftRoot(layoutHash = 0x{:016x}uL, safeArea = {}{theme_arg}{tabs_arg}, make = ::makeScope)",
        layout.hash(),
        layout.safe_area()
    ));
    if program.app.is_some() {
        out.close("}");
    }
    out.close("}");
    out.writer.blank();
    out.writer.line("/** Scope of a `create` op. */");
    out.open("private fun makeScope(template: Int, id: Int, session: WeftSession): WeftScope? = when (template) {");
    for index in 0..layout.templates().len() {
        out.writer
            .line(format_args!("{index} -> S{index}(id, session)"));
    }
    out.writer.line("else -> null");
    out.close("}");
    for (index, template) in layout.templates().iter().enumerate() {
        out.writer.blank();
        out.writer
            .line(format_args!("// {index} {}", template.label));
        out.writer.blank();
        scope(&mut out, index, template);
        out.writer.blank();
        view::view(&mut out, index, template);
        if view::has_navigation_bar(template) {
            out.writer.blank();
            view::navigation_bar(&mut out, index, template);
        }
    }
    out.writer.finish()
}

/// The scope class `S{index}` of `template`.
fn scope(out: &mut Code, index: usize, template: &Template) {
    out.open(format_args!(
        "private class S{index}(id: Int, session: WeftSession) : WeftScope(id, session) {{"
    ));
    for (slot, value) in template.values.iter().enumerate() {
        let ViewNodeKind::Element { element, .. } = &template.nodes[value.node as usize].kind
        else {
            unreachable!("value slots belong to elements");
        };
        out.writer
            .line(format_args!("/** {}.{} */", element.name(), value.prop));
        let state = match value.ty {
            ValueType::Int | ValueType::Float => "mutableFloatStateOf(0f)",
            ValueType::Bool => "mutableStateOf(false)",
            ValueType::String => "mutableStateOf(\"\")",
            ValueType::Color => "mutableStateOf(WeftColor.Transparent)",
            ValueType::Strings => "mutableStateOf<List<String>>(emptyList())",
        };
        out.writer.line(format_args!("var v{slot} by {state}"));
    }
    for (point, mount) in template.points.iter().enumerate() {
        match &mount.kind {
            PointKind::Branch { .. } | PointKind::Slot => out.writer.line(format_args!(
                "var p{point} by mutableStateOf<WeftScope?>(null)"
            )),
            PointKind::List { template } => out.writer.line(format_args!(
                "var p{point} by mutableStateOf<List<S{}>>(emptyList())",
                template.0
            )),
            PointKind::Lazy { .. } => {
                unreachable!("lazy lists are not supported on native platforms")
            }
            PointKind::Instance { template } => out.writer.line(format_args!(
                "var p{point} by mutableStateOf<S{}?>(null)",
                template.0
            )),
        }
    }
    if !template.values.is_empty() {
        out.writer.blank();
        out.open("override fun apply(slot: Int, value: WeftValue) {");
        out.open("when (slot) {");
        for (slot, value) in template.values.iter().enumerate() {
            let accessor = match value.ty {
                ValueType::Int | ValueType::Float => "number",
                ValueType::Bool => "bool",
                ValueType::String => "string",
                ValueType::Color => "color",
                ValueType::Strings => "strings",
            };
            out.writer
                .line(format_args!("{slot} -> v{slot} = value.{accessor}"));
        }
        out.close("}");
        out.close("}");
    }
    if !template.points.is_empty() {
        out.writer.blank();
        out.open("override fun mount(point: Int, children: List<WeftScope>) {");
        out.open("when (point) {");
        for (point, mount) in template.points.iter().enumerate() {
            match &mount.kind {
                PointKind::Branch { .. } | PointKind::Slot => out
                    .writer
                    .line(format_args!("{point} -> p{point} = children.firstOrNull()")),
                PointKind::List { template } => out.writer.line(format_args!(
                    "{point} -> p{point} = children.map {{ it as S{} }}",
                    template.0
                )),
                PointKind::Lazy { .. } => {
                    unreachable!("lazy lists are not supported on native platforms")
                }
                PointKind::Instance { template } => out.writer.line(format_args!(
                    "{point} -> p{point} = children.firstOrNull() as S{}?",
                    template.0
                )),
            }
        }
        out.close("}");
        out.close("}");
    }
    if !template.values.is_empty() || !template.points.is_empty() {
        out.writer.blank();
    }
    if template.kind == TemplateKind::Page {
        out.writer.line("override val isPage: Boolean get() = true");
        if view::has_navigation_bar(template) {
            out.writer.line("@Composable");
            out.writer.line(format_args!(
                "override fun NavigationBar(onBack: (() -> Unit)?) = Bar{index}(this, onBack)"
            ));
        }
    }
    out.writer.line("@Composable");
    out.writer
        .line(format_args!("override fun Content() = V{index}(this)"));
    out.close("}");
}

#[cfg(test)]
mod tests {
    use super::*;
    use weft_ui_parser::MemoryLoader;

    #[test]
    fn root_uses_the_app_safe_area_option() {
        use crate::{AppOptions, compile_app, transform::Platform};

        let mut loader = MemoryLoader::new();
        loader.insert("App.weft", r#"component App() { Text("hello") }"#);
        for options in [
            AppOptions::default(),
            AppOptions {
                safe_area: false,
                ..AppOptions::default()
            },
        ] {
            let output = compile_app(
                weft_ui_parser::load(&["App.weft"], &mut loader),
                Platform::Android,
                &options,
            );
            assert!(
                !output.compilation.has_errors(),
                "{}",
                output.compilation.render_diagnostics()
            );
            let view = output
                .views
                .iter()
                .find(|view| view.path == VIEWS)
                .expect("Android compilation emits the Compose views");
            assert!(
                view.contents
                    .contains(&format!(", safeArea = {},", options.safe_area)),
                "{}",
                view.contents
            );
        }
    }

    #[test]
    fn page_navigation_bar_uses_live_slots_and_is_not_content() {
        let mut loader = MemoryLoader::new();
        loader.insert(
            "App.weft",
            r#"
                event Action()
                app Notes { start = Home }
                page Home() { Text("home") }
                page Detail(title: String, disabled: Bool) {
                    NavBar(title = title) {
                        BarButton(label = "Action", disabled = disabled, onTap = Action())
                    }
                    Text("body")
                }
            "#,
        );
        let compilation = crate::check(weft_ui_parser::load(&["App.weft"], &mut loader));
        let Some(program) = &compilation.program else {
            panic!("{}", compilation.render_diagnostics());
        };
        let code = generate(&ViewLayout::new(program), program);
        assert!(
            code.contains("override val isPage: Boolean get() = true"),
            "{code}"
        );
        assert!(
            code.contains("override fun NavigationBar(onBack: (() -> Unit)?)"),
            "{code}"
        );
        assert!(
            code.contains("WeftNavigationBar(title = s.v0, hidden = false, onBack = onBack)"),
            "{code}"
        );
        assert!(code.contains("WeftBarButton(title = \"Action\", icon = null, enabled = !(s.v1), onClick = { s.dispatch(0) })"), "{code}");
        assert!(code.contains("WeftText(\"body\")"), "{code}");
        assert!(!code.contains("WeftNavBar"), "{code}");
    }

    #[test]
    fn strings_are_escaped_and_never_interpolated() {
        let mut loader = MemoryLoader::new();
        loader.insert(
            "App.weft",
            r#"component A() { Text("say \"hi\" \\ $name \${x} \n\r\t\u{8}\u{7} café") }"#,
        );
        let compilation = crate::check(weft_ui_parser::load(&["App.weft"], &mut loader));
        let Some(program) = &compilation.program else {
            panic!("{}", compilation.render_diagnostics());
        };
        let code = generate(&ViewLayout::new(program), program);
        assert!(
            code.contains(r#"WeftText("say \"hi\" \\ \$name \${x} \n\r\t\b\u0007 café")"#),
            "{code}"
        );
    }
}
