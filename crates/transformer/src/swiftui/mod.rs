//! SwiftUI backend for iOS and macOS.
//!
//! The native kernel runs the logic from
//! [`crate::bridge::remote_module`].
//! Its ops drive the view layer: `Generated.swift`, one Swift file for the
//! whole app, compiled into the `WeftApp` package of `apps/<platform>/weft/`
//! against `WeftKit` (`native/apple`). Both platforms get the same code; the
//! few differences (AppKit or UIKit controls) live in WeftKit.
//!
//! Every layout template `n` becomes
//!
//! - `S{n}`, an `@Observable` subclass of `WeftScope` with one property per
//!   value slot (`v{i}`) and mount point (`p{i}`), and the `apply` / `mount`
//!   overrides the session calls for `set` and `branch` / `rows` / `attach`
//!   ops;
//! - `V{n}`, the SwiftUI view of one scope: the static tree with constants
//!   inlined, reading the scope's properties, so SwiftUI only re-renders the
//!   views whose properties changed.
//!
//! The public entry point is `WeftAppView`, which starts the kernel with the
//! bundle and renders the root component.

mod swift;
mod view;

use crate::transform::{Context, OutputFile};
use crate::view::{PointKind, Template, ValueType, ViewLayout, ViewNodeKind};

use swift::Code;

/// Path of the generated views, relative to `apps/<platform>/weft/`.
const VIEWS: &str = "Generated.swift";

/// Generates the SwiftUI views shared by iOS and macOS.
///
/// # Panics
///
/// Panics without a layout in `cx`.
#[must_use]
pub fn transform(cx: &Context<'_>) -> Vec<OutputFile> {
    let layout = cx.layout.expect("the SwiftUI views need the layout");
    vec![OutputFile {
        path: VIEWS.to_owned(),
        contents: generate(layout, cx.program.app.as_ref()),
    }]
}

fn generate(layout: &ViewLayout, app: Option<&crate::ir::Application>) -> String {
    let mut out = Code::new();
    out.writer
        .line("// Generated by Weft UI from the app's .weft files; every build rewrites it.");
    out.writer.blank();
    out.writer.line("import SwiftUI");
    out.writer.line("import WeftKit");
    out.writer.blank();
    out.writer.line(
        "/// The app's kernel session, started on first use with the bundle of this package.",
    );
    let theme = layout.theme();
    if !theme.is_empty() {
        out.open("@MainActor private let session: WeftSession = {");
        out.open("WeftTheme.register([");
        for (name, light, dark) in theme {
            // Theme names are ASCII identifiers, so they never need escaping.
            let (light, dark) = (swift::rgba(*light), swift::rgba(*dark));
            out.writer
                .line(format_args!("\"{name}\": ({light}, {dark}),"));
        }
        out.close("])");
    }
    let session = if theme.is_empty() {
        "@MainActor private let session = WeftSession("
    } else {
        "return WeftSession("
    };
    out.open(session);
    out.writer
        .line("bytecode: Bundle.module.url(forResource: \"bundle\", withExtension: \"hbc\"),");
    out.writer.line("resources: Bundle.module,");
    out.writer
        .line(format_args!("layoutHash: 0x{:016x},", layout.hash()));
    out.writer
        .line(format_args!("safeArea: {},", layout.safe_area()));
    if let Some(tabs) = app.and_then(|app| app.tabs.as_ref()) {
        out.open("tabs: [");
        for tab in tabs {
            let title = std::fmt::from_fn(|f| swift::string(f, &tab.title));
            let icon = std::fmt::from_fn(|f| {
                swift::string(f, tab.icon.strip_prefix("asset:").unwrap_or(&tab.icon))
            });
            let active_icon = std::fmt::from_fn(|f| {
                swift::string(
                    f,
                    tab.active_icon
                        .strip_prefix("asset:")
                        .unwrap_or(&tab.active_icon),
                )
            });
            out.writer.line(format_args!(
                "WeftTab(title: {title}, icon: {icon}, activeIcon: {active_icon}),"
            ));
        }
        out.close("],");
    }
    out.writer.line("make: makeScope");
    out.close(")");
    if !theme.is_empty() {
        out.close("}()");
    }
    out.writer.blank();
    out.writer.line("/// Root view of the app.");
    out.open("public struct WeftAppView: View {");
    out.writer.line("public init() {}");
    out.writer.blank();
    out.open("public var body: some View {");
    out.writer.line("WeftRoot(session: session)");
    out.close("}");
    out.close("}");
    out.writer.blank();
    out.writer.line("/// Scope of a `create` op.");
    out.open(
        "@MainActor private func makeScope(template: UInt32, id: UInt32, session: WeftSession) -> WeftScope? {",
    );
    out.writer.line("switch template {");
    for index in 0..layout.templates().len() {
        out.writer.line(format_args!(
            "case {index}: S{index}(id: id, session: session)"
        ));
    }
    out.writer.line("default: nil");
    out.writer.line("}");
    out.close("}");
    for (index, template) in layout.templates().iter().enumerate() {
        out.writer.blank();
        out.writer
            .line(format_args!("// MARK: - {index} {}", template.label));
        out.writer.blank();
        scope(&mut out, index, template);
        out.writer.blank();
        view::view(&mut out, index, template);
    }
    out.writer.finish()
}

/// The scope class `S{index}` of `template`.
fn scope(out: &mut Code, index: usize, template: &Template) {
    out.open(format_args!(
        "@Observable private final class S{index}: WeftScope {{"
    ));
    for (slot, value) in template.values.iter().enumerate() {
        let ViewNodeKind::Element { element, .. } = &template.nodes[value.node as usize].kind
        else {
            unreachable!("value slots belong to elements");
        };
        out.writer
            .line(format_args!("/// {}.{}", element.name(), value.prop));
        let declaration = match value.ty {
            ValueType::Int | ValueType::Float => "CGFloat = 0",
            ValueType::Bool => "Bool = false",
            ValueType::String => "String = \"\"",
            ValueType::Color => "WeftColor = .clear",
            ValueType::Strings => "[String] = []",
        };
        out.writer.line(format_args!("var v{slot}: {declaration}"));
    }
    for (point, mount) in template.points.iter().enumerate() {
        let declaration = match &mount.kind {
            PointKind::Branch { .. } | PointKind::Slot => "WeftScope?".to_owned(),
            PointKind::List { template } => format!("[S{}] = []", template.0),
            PointKind::Instance { template } => format!("S{}?", template.0),
        };
        out.writer.line(format_args!("var p{point}: {declaration}"));
    }
    if !template.values.is_empty() {
        out.writer.blank();
        out.open("override func apply(_ slot: Int, _ value: WeftValue) {");
        out.writer.line("switch slot {");
        for (slot, value) in template.values.iter().enumerate() {
            let accessor = match value.ty {
                ValueType::Int | ValueType::Float => "length",
                ValueType::Bool => "bool",
                ValueType::String => "string",
                ValueType::Color => "color",
                ValueType::Strings => "strings",
            };
            out.writer
                .line(format_args!("case {slot}: v{slot} = value.{accessor}"));
        }
        out.writer.line("default: break");
        out.writer.line("}");
        out.close("}");
    }
    if !template.points.is_empty() {
        out.writer.blank();
        out.open("override func mount(_ point: Int, _ children: [WeftScope]) {");
        out.writer.line("switch point {");
        for (point, mount) in template.points.iter().enumerate() {
            let value = match &mount.kind {
                PointKind::Branch { .. } | PointKind::Slot => "children.first".to_owned(),
                PointKind::List { template } => {
                    format!("children.map {{ $0 as! S{} }}", template.0)
                }
                PointKind::Instance { template } => {
                    format!("children.first.map {{ $0 as! S{} }}", template.0)
                }
            };
            out.writer
                .line(format_args!("case {point}: p{point} = {value}"));
        }
        out.writer.line("default: break");
        out.writer.line("}");
        out.close("}");
    }
    out.writer.blank();
    out.writer.line(format_args!(
        "override var view: AnyView {{ AnyView(V{index}(s: self)) }}"
    ));
    if view::has_navbar(template) {
        out.writer.line("#if os(macOS)");
        out.writer.line(format_args!(
            "override var modalBar: AnyView {{ AnyView(V{index}(s: self).modalBar) }}"
        ));
        out.writer.line(format_args!(
            "override var modalBarHidden: Bool {{ V{index}(s: self).modalBarHidden }}"
        ));
        out.writer.line("#endif");
    }
    out.close("}");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::AppOptions;
    use weft_ui_parser::MemoryLoader;

    fn swift(source: &str, options: &AppOptions) -> String {
        let mut loader = MemoryLoader::new();
        loader.insert("App.weft", source);
        let compilation = crate::check(weft_ui_parser::load(&["App.weft"], &mut loader));
        let Some(program) = &compilation.program else {
            panic!("{}", compilation.render_diagnostics());
        };
        generate(
            &ViewLayout::for_platform(program, None, options),
            program.app.as_ref(),
        )
    }

    #[test]
    fn safe_area_is_registered_with_the_session() {
        let source = "component App() { Text(\"Safe area\") }";
        let default = swift(source, &AppOptions::default());
        let edge_to_edge = swift(
            source,
            &AppOptions {
                safe_area: false,
                ..AppOptions::default()
            },
        );
        assert!(default.contains("safeArea: true,\n"), "{default}");
        assert!(
            edge_to_edge.contains("safeArea: false,\n"),
            "{edge_to_edge}"
        );
    }

    #[test]
    fn strings_are_escaped_and_never_interpolated() {
        let code = swift(
            r#"component A() { Text("say \"hi\" \\(x) \u{7}") }"#,
            &AppOptions::default(),
        );
        assert!(
            code.contains(r#"weftText(spans: [.init(value: "say \"hi\" \\(x) \u{7}")])"#),
            "{code}"
        );
    }
}
