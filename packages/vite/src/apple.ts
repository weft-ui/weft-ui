import { existsSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import type { NativeAdapter, RunTool } from "./native.ts";

/**
 * `weft/Package.swift`: the generated area as the local package `WeftApp`
 * that the Xcode template links. It compiles the generated views with the
 * bytecode as a resource, against WeftKit at `kit`.
 */
function packageManifest(kit: string, generated: string): string {
  const resources = ['.copy("bundle.hbc")'];
  if (existsSync(join(generated, "Assets.xcassets"))) resources.push('.process("Assets.xcassets")');
  if (existsSync(join(generated, "fonts"))) resources.push('.copy("fonts")');
  // Package identities of path dependencies are their directory names.
  return `// swift-tools-version: 6.0
// Generated by @weft-ui/vite: the app's views and bundle; every build rewrites it.

import PackageDescription

let package = Package(
    name: "WeftApp",
    platforms: [.macOS(.v14), .iOS(.v17)],
    products: [
        .library(name: "WeftApp", targets: ["WeftApp"]),
    ],
    dependencies: [
        .package(path: ${JSON.stringify(kit)}),
    ],
    targets: [
        .target(
            name: "WeftApp",
            dependencies: [.product(name: "WeftKit", package: ${JSON.stringify(basename(kit))})],
            path: ".",
            exclude: ["js", "layout.json", "Info.plist", "App.entitlements"],
            sources: ["Generated.swift"],
            resources: [${resources.join(", ")}]
        ),
    ]
)
`;
}

function xml(value: string): string {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&apos;");
}

/** Write the Xcode-merged URL registration and signing entitlements. */
export function writeAppleLinks(generated: string, links: { scheme?: string; hosts?: string[] } = {}): void {
  const plist = (body: string) => `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n${body}</dict>\n</plist>\n`;
  const urls = links.scheme ? `  <key>CFBundleURLTypes</key>\n  <array><dict><key>CFBundleURLSchemes</key><array><string>${xml(links.scheme)}</string></array></dict></array>\n` : "";
  const domains = links.hosts?.length ? `  <key>com.apple.developer.associated-domains</key>\n  <array>\n${links.hosts.map((host) => `    <string>applinks:${xml(host)}</string>\n`).join("")}  </array>\n` : "";
  writeFileSync(join(generated, "Info.plist"), plist(urls));
  writeFileSync(join(generated, "App.entitlements"), plist(domains));
}

export function appleAdapter(runTool: RunTool, kit: string): NativeAdapter {
  return {
    bytecode: "bundle.hbc",
    host: "darwin",
    hostWarning: "xcodebuild needs macOS",
    writeGlue(generated, _project, links) {
      writeAppleLinks(generated, links);
      writeFileSync(join(generated, "Package.swift"), packageManifest(kit, generated));
    },
    // Build for the iOS simulator in debug builds, or a device in release builds (which need signing).
    async build(project, platform, release) {
      const core = join(kit, "build/WeftCore.xcframework");
      if (!existsSync(core)) {
        throw new Error(`weft: the native kernel for Apple platforms is missing (${core}); build it with native/apple/build-core.sh`);
      }
      const destination = platform === "macos"
        ? "generic/platform=macOS"
        : release ? "generic/platform=iOS" : "generic/platform=iOS Simulator";
      const args = [
        "-project", "App.xcodeproj",
        "-scheme", "App",
        "-configuration", release ? "Release" : "Debug",
        "-destination", destination,
        "-derivedDataPath", "build",
        "-quiet",
        "build",
      ];
      await runTool("xcodebuild", args, { cwd: project, lineSeparator: "\n" }, {
        missing: "weft: xcodebuild not found; install Xcode and select it with `sudo xcode-select -s /Applications/Xcode.app`",
        failed: `weft: xcodebuild failed in ${project}`,
      });
    },
  };
}
