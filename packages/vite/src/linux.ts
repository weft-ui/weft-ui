import { writeFileSync } from "node:fs";
import { isAbsolute, join, relative } from "node:path";
import type { NativeAdapter, RunTool } from "./native.ts";

function escapeCmakeString(value: string): string {
  return value.replaceAll("\\", "/").replaceAll("$", "\\$").replaceAll('"', '\\"');
}

/**
 * `weft/CMakeLists.txt`: added by the CMake project of the Linux template.
 * It adds the shell (referenced relative to the generated directory
 * `generated`, so the project builds wherever the workspace is) and builds
 * the generated views (`weft/Generated.cpp`) with the bytecode for the
 * template's `weft_app()` calls.
 */
function cmakeLists(generated: string, shell: string): string {
  const path = relative(generated, shell);
  const escaped = escapeCmakeString(path);
  const target = isAbsolute(path) ? escaped : `\${CMAKE_CURRENT_LIST_DIR}/${escaped}`;
  return `# Generated by @weft-ui/vite: the app's views and bundle and the Weft shell; every build rewrites it.

add_subdirectory("${target}" weft-linux)
weft_views("\${CMAKE_CURRENT_LIST_DIR}/Generated.cpp" "\${CMAKE_CURRENT_LIST_DIR}/bundle.hbc" "\${CMAKE_CURRENT_LIST_DIR}/assets")
`;
}

export function linuxAdapter(runTool: RunTool, shell: string): NativeAdapter {
  return {
    bytecode: "bundle.hbc",
    host: "linux",
    hostWarning: "the Linux build needs a Linux host",
    writeGlue(generated) {
      writeFileSync(join(generated, "CMakeLists.txt"), cmakeLists(generated, shell));
    },
    // Configure first, then build the executable at project/build/app.
    async build(project, _platform, release) {
      const options = { cwd: project };
      const messages = {
        missing: "weft: cmake not found; install CMake, a C++ compiler and the GTK 4 development packages " +
          "(on Debian and Ubuntu: `sudo apt install build-essential cmake pkg-config libgtk-4-dev libsoup-3.0-dev libjson-glib-dev libfontconfig-dev librsvg2-common`)",
        failed: `weft: the CMake build failed in ${project}`,
      };
      await runTool("cmake", ["-S", ".", "-B", "build", `-DCMAKE_BUILD_TYPE=${release ? "Release" : "Debug"}`], options, messages);
      await runTool("cmake", ["--build", "build", "--parallel"], options, messages);
    },
  };
}
