import { existsSync, writeFileSync } from "node:fs";
import { isAbsolute, join, relative } from "node:path";
import type { NativeAdapter, RunTool } from "./native.ts";

/**
 * `weft/Weft.targets`: imported by the app project of the Windows template.
 * It links Weft.WinUI and the kernel (`Weft.WinUI.targets` in `shell`) and
 * copies the bytecode next to the executable; the generated views
 * (`weft/Generated.cs`) are compiled as part of the project. The shell is
 * referenced relative to the generated directory `generated`.
 */
function escapeMsBuildAttr(value: string): string {
  const entities: Record<string, string> = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" };
  return value
    .replace(/[%$@;?*']/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`)
    .replace(/[&<>"']/g, (c) => entities[c]!);
}

function targets(generated: string, shell: string): string {
  // On another drive the relative path is absolute.
  const path = relative(generated, shell);
  const escaped = escapeMsBuildAttr(path);
  const location = (isAbsolute(path) ? escaped : `$(MSBuildThisFileDirectory)${escaped}`).replaceAll("/", "\\");
  const assets = existsSync(join(generated, "assets"))
    ? '\n    <Content Include="$(MSBuildThisFileDirectory)assets\\**\\*" Link="weft\\assets\\%(RecursiveDir)%(Filename)%(Extension)" CopyToOutputDirectory="PreserveNewest" />'
    : "";
  return `<Project>

  <!-- Generated by @weft-ui/vite: the app's views and bundle; every build rewrites it. -->
  <Import Project="${location}\\Weft.WinUI.targets" />

  <ItemGroup>
    <Content Include="$(MSBuildThisFileDirectory)bundle.hbc" Link="weft\\bundle.hbc" CopyToOutputDirectory="PreserveNewest" />${assets}
  </ItemGroup>

</Project>
`;
}

export function windowsAdapter(runTool: RunTool, shell: string): NativeAdapter {
  return {
    bytecode: "bundle.hbc",
    host: "win32",
    hostWarning: "the Windows build needs a Windows host",
    writeGlue(generated) {
      writeFileSync(join(generated, "Weft.targets"), targets(generated, shell));
    },
    async build(project, _platform, release) {
      const args = ["build", "App.csproj", "-c", release ? "Release" : "Debug", "-nologo", "-v", "quiet"];
      await runTool("dotnet", args, { cwd: project }, {
        missing: "weft: dotnet not found; install the .NET 10 SDK (`winget install Microsoft.DotNet.SDK.10`)",
        failed: `weft: dotnet build failed in ${project}`,
      });
    },
  };
}
