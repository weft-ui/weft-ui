import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, relative } from "node:path";
import type { NativeAdapter, RunTool } from "./native.ts";

/**
 * `weft/settings.gradle.kts`: applied by the settings of the Android
 * template. It includes the generated area as the module `:weft` and the
 * shell as `:weft-android`, referenced relative to the project directory
 * `project` so the project builds wherever the workspace is.
 */
function settingsFragment(project: string, shell: string): string {
  // On another drive the relative path is absolute; `resolve` keeps absolute paths.
  const path = relative(project, shell).replaceAll("\\", "/");
  return `// Generated by @weft-ui/vite: the app's views and bundle and the Weft shell; every build rewrites it.

include(":weft")
include(":weft-android")
project(":weft-android").projectDir = settingsDir.resolve(${JSON.stringify(path).replaceAll("$", "\\$")})
`;
}

/**
 * `weft/build.gradle.kts`: the generated area as an Android library module
 * in the standard layout: the views (`src/main/kotlin/Generated.kt`) and the
 * bytecode as an asset, on top of the shell, which it exposes to the app.
 */
function moduleBuild(): string {
  return `// Generated by @weft-ui/vite: the app's views and bundle; every build rewrites it.

plugins {
    id("com.android.library")
    id("org.jetbrains.kotlin.plugin.compose")
}

// Builds rewrite weft/, so the Gradle outputs go to the app's build directory.
layout.buildDirectory.set(rootProject.layout.buildDirectory.dir("weft"))

android {
    namespace = "net.mioyi.weftui.generated"
    compileSdk = 37
    defaultConfig {
        minSdk = 24
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
    }
}

dependencies {
    api(project(":weft-android"))
}
`;
}

function linkManifest(links: { scheme?: string; hosts?: string[] }): string {
  const escape = (value: string) => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
  const filter = (data: string, verified = false) => `            <intent-filter${verified ? ' android:autoVerify="true"' : ""}>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                ${data}
            </intent-filter>`;
  const filters = [
    ...(links.scheme ? [filter(`<data android:scheme="${escape(links.scheme)}" />`)] : []),
    ...(links.hosts ?? []).map((host) => filter(`<data android:scheme="https" android:host="${escape(host)}" />`, true)),
  ];
  return `<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
${filters.length ? `    <application>
        <activity android:name="net.mioyi.weftui.generated.WeftLinkActivity" android:exported="true" android:theme="@android:style/Theme.NoDisplay">
${filters.join("\n")}
        </activity>
    </application>\n` : ""}</manifest>
`;
}

const linkActivity = `package net.mioyi.weftui.generated

import android.app.Activity
import android.content.Intent
import android.os.Bundle

class WeftLinkActivity : Activity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val launch = packageManager.getLaunchIntentForPackage(packageName)
        if (launch != null && intent.data != null) {
            launch.data = intent.data
            launch.addFlags(Intent.FLAG_ACTIVITY_SINGLE_TOP)
            startActivity(launch)
        }
        finish()
    }
}
`;

/** The Android SDK named by the environment, `local.properties` of `project`, or the default install location. */
function androidSdk(project: string): string | undefined {
  const fromEnv = process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT;
  if (fromEnv) return fromEnv;
  const properties = join(project, "local.properties");
  if (existsSync(properties)) {
    const dir = /^sdk\.dir=(.*)$/m.exec(readFileSync(properties, "utf8"))?.[1];
    if (dir) return dir.replaceAll("\\:", ":").replaceAll("\\\\", "\\").trim();
  }
  const defaults: Partial<Record<NodeJS.Platform, string>> = {
    darwin: join(homedir(), "Library/Android/sdk"),
    linux: join(homedir(), "Android/Sdk"),
    win32: join(process.env.LOCALAPPDATA ?? join(homedir(), "AppData/Local"), "Android/Sdk"),
  };
  const fallback = defaults[process.platform];
  return fallback && existsSync(fallback) ? fallback : undefined;
}

export function androidAdapter(runTool: RunTool, shell: string): NativeAdapter {
  return {
    // The Android module packages the bytecode as an asset.
    bytecode: "src/main/assets/weft/bundle.hbc",
    writeGlue(generated, project, links) {
      writeFileSync(join(generated, "settings.gradle.kts"), settingsFragment(project, shell));
      writeFileSync(join(generated, "build.gradle.kts"), moduleBuild());
      const main = join(generated, "src/main");
      const kotlin = join(main, "kotlin/net/mioyi/weftui/generated");
      mkdirSync(kotlin, { recursive: true });
      writeFileSync(join(main, "AndroidManifest.xml"), linkManifest(links));
      writeFileSync(join(kotlin, "WeftLinkActivity.kt"), linkActivity);
    },
    // The APK is in project/app/build/outputs/apk/; release builds are unsigned unless the project configures signing.
    async build(project, _platform, release) {
      const kernel = join(shell, "build/jniLibs");
      if (!existsSync(kernel)) {
        throw new Error(`weft: the native kernel for Android is missing (${kernel}); build it with native/android/build-core.sh`);
      }
      const sdk = androidSdk(project);
      if (!sdk) {
        throw new Error(
          "weft: the Android SDK was not found; install it (e.g. with Android Studio) and set ANDROID_HOME, " +
            `or write sdk.dir=<path> to ${join(project, "local.properties")}`,
        );
      }
      const windows = process.platform === "win32";
      const wrapper = join(project, windows ? "gradlew.bat" : "gradlew");
      const args = [release ? "assembleRelease" : "assembleDebug", "--quiet", "--console=plain"];
      if (windows && wrapper.includes('"')) {
        throw new Error(`weft: Gradle wrapper path cannot contain \`"\`: ${wrapper}`);
      }
      await runTool(
        windows ? (process.env.ComSpec ?? "cmd.exe") : wrapper,
        windows ? ["/d", "/s", "/c", `""${wrapper}" ${args.join(" ")}"`] : args,
        {
          cwd: project,
          env: { ...process.env, ANDROID_HOME: sdk },
          ...(windows ? { windowsVerbatimArguments: true } : {}),
        },
        {
          missing: `weft: the Gradle wrapper is missing (${wrapper}); restore it from the Android template`,
          failed: `weft: the Gradle build failed in ${project}`,
        },
      );
    },
  };
}
