import { writeFileSync } from "node:fs";
import { componentName, pages, platforms } from "./pages.ts";

const platform = platforms.find((name) => name === process.argv[2]);
if (!platform) throw new Error(`Usage: node scripts/catalog.ts <${platforms.join("|")}>`);

const fields = new Set<string>();
for (const { id, props } of pages()) {
  if (props === undefined) continue;
  if (!props || typeof props !== "object" || Array.isArray(props)) {
    throw new Error(`${id}.props must be an object`);
  }
  for (const [name, value] of Object.entries(props)) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`${id}.props: invalid field name ${JSON.stringify(name)}`);
    if (!Array.isArray(value) || value.some((item) => typeof item !== "string")) {
      throw new Error(`${id}.props.${name} must be a string array`);
    }
    if (fields.has(name)) throw new Error(`${id}.props.${name}: duplicate showcase field`);
    fields.add(name);
  }
}

const catalog = pages(platform).map(({ id, title, component, props }) => {
  const file = id.split(/[-_]/).map((word) => word[0]!.toUpperCase() + word.slice(1)).join("");
  const args = id === "safearea" ? "model.safeArea" : Object.keys(props ?? {}).map((name) => `model.${name}`).join(", ");
  const name = componentName({ id, title, component, props });
  return { id, title, file, name, page: `${name}Page`, args };
});

writeFileSync(new URL("../src/App.weft", import.meta.url), [
  "// Generated by scripts/catalog.ts from pages.json.",
  ...catalog.map(({ file }) => `import "./pages/${file}.weft"`),
  "",
  `model ShowcaseModel { safeArea: ShowcaseInsets, ${[...fields].map((name) => `${name}: String[]`).join(", ")} }`,
  "event Open(id: String)",
  "",
  "page Catalog() {",
  '    NavBar(title = "Showcase")',
  "    Scroll {",
  "        Column(padding = 16, gap = 8) {",
  ...catalog.map(({ id }) => `            Button(onClick = { Open(${JSON.stringify(id)}) }) { Text(${JSON.stringify(`page:${id}`)}) }`),
  "        }",
  "    }",
  "}",
  ...catalog.map(({ id, title, name, page, args }) => `page ${page}(model: ShowcaseModel) path ${JSON.stringify(`/showcase/${id}`)} {\n    NavBar(title = ${JSON.stringify(title)})\n    ${name}(${args})\n}`),
  "",
  "app Example { start = Catalog }",
  "",
].join("\n"));

writeFileSync(new URL("../src/catalog.ts", import.meta.url), [
  "// Generated by scripts/catalog.ts from pages.json.",
  'import { navigation, platform } from "@weft-ui/platform";',
  'import manifest from "../pages.json" with { type: "json" };',
  `import { Example, Catalog, ${catalog.map(({ page }) => page).join(", ")} } from "./App.weft";`,
  'import { setup } from "./setup.ts";',
  "",
  `type Model = ConstructorParameters<typeof ${catalog[0]!.page}>[0];`,
  'const props = Object.fromEntries(manifest.flatMap(({ props }) => Object.entries(props ?? {}))) as Record<Exclude<keyof Model, "safeArea">, string[]>;',
  // A page pending on this platform is absent from App.weft, so setup.ts may name pages this catalog lacks.
  "const handlers: Partial<Record<string, (page: never) => void>> = setup;",
  "",
  "export const app = new Example({",
  "  Catalog: () => {",
  "    const page = new Catalog({});",
  "    page.onOpen((_, event) => {",
  "      switch (event.id) {",
  ...catalog.map(({ id, page }) => `        case ${JSON.stringify(id)}: navigation.push(${page}); break;`),
  "      }",
  "    });",
  "    return page;",
  "  },",
  ...catalog.flatMap(({ id, page }) => [
    `  ${page}: () => {`,
    `    const page = new ${page}({ ...props, safeArea: platform.safeArea }, {});`,
    `    (handlers[${JSON.stringify(id)}] as ((page: ${page}) => void) | undefined)?.(page);`,
    "    return page;",
    "  },",
  ]),
  "});",
  "",
].join("\n"));
